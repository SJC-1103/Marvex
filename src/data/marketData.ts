/**
 * Deterministic PRNG seeded generator for consistent, reproducible historical daily bars
 */
function generateDailyBars(
  basePrice: number,
  targetDays = 760,
  annualVol = 0.22,
  annualDrift = 0.14
): DailyBar[] {
  const bars: DailyBar[] = [];
  const dailyVol = annualVol / Math.sqrt(252);
  const dailyDrift = annualDrift / 252;

  // Start date: roughly 3 calendar years back
  const currentDate = new Date('2026-10-14T00:00:00Z');
  let currentPrice = basePrice * Math.exp(-annualDrift * 3); // initial price 3 years ago

  // Simple deterministic LCG
  let seed = Math.round(basePrice * 100);
  const nextRandom = () => {
    seed = (seed * 9301 + 49297) % 233280;
    return seed / 233280;
  };

  const dates: string[] = [];
  const tempDate = new Date(currentDate);

  // Generate business days going backwards, then reverse
  while (dates.length < targetDays) {
    tempDate.setDate(tempDate.getDate() - 1);
    const day = tempDate.getUTCDay();
    if (day !== 0 && day !== 6) {
      dates.push(tempDate.toISOString().split('T')[0]);
    }
  }
  dates.reverse();

  for (let i = 0; i < dates.length; i++) {
    const u1 = nextRandom();
    const u2 = nextRandom();
    const z = Math.sqrt(-2.0 * Math.log(u1 || 0.0001)) * Math.cos(2.0 * Math.PI * u2);

    const ret = dailyDrift + dailyVol * z;
    const open = currentPrice;
    const close = Math.max(0.1, open * (1 + ret));
    const intraHigh = Math.max(open, close) * (1 + nextRandom() * dailyVol * 0.8);
    const intraLow = Math.min(open, close) * (1 - nextRandom() * dailyVol * 0.8);
    const volume = Math.round(150000 + nextRandom() * 950000);

    bars.push({
      date: dates[i],
      open: Number(open.toFixed(2)),
      high: Number(intraHigh.toFixed(2)),
      low: Number(intraLow.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });

    currentPrice = close;
  }

  // Adjust last bar close to match the requested basePrice exactly
  if (bars.length > 0) {
    const last = bars[bars.length - 1];
    const factor = basePrice / (last.close || 1);
    bars.forEach(b => {
      b.open = Number((b.open * factor).toFixed(2));
      b.high = Number((b.high * factor).toFixed(2));
      b.low = Number((b.low * factor).toFixed(2));
      b.close = Number((b.close * factor).toFixed(2));
    });
  }

  return bars;
}

